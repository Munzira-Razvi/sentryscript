import json
import uuid
from engine import fmt_duration

def q(value):
    """JSON strings and numbers are valid YAML scalars."""
    return json.dumps(value)

def _id(name):
    return str(uuid.uuid5(uuid.NAMESPACE_URL, "sentryscript/" + name))

def _clock(minutes):
    return f"{minutes // 60:02d}:{minutes % 60:02d}"

def rule_to_sigma(rule):
    selection = {"type": rule.event}
    negated = []
    for f in rule.filters:
        if f.op in ("==", "in"):
            selection[f.field] = f.value
        else:
            negated.append({f.field: f.value})

    base_name = f"{rule.name}_events"
    description = f"Generated by SentryScript from rule '{rule.name}'."
    if rule.kind == "time":
        where = "Outside" if rule.negate else "Inside"
        description += (f" Only matches events {where.lower()} "
                        f"{_clock(rule.start)}..{_clock(rule.end)} (time of day). "
                        "Sigma has no time-of-day condition: apply this time "
                        "filter in your SIEM query.")

    title = rule.name if rule.kind == "time" else f"{rule.name} - matching events"

    base = [
        f"title: {q(title)}",
        f"name: {base_name}",
        f"id: {_id(base_name)}",
        "status: experimental",
        f"description: {q(description)}",
        "logsource:",
        "    product: generic",
        "detection:",
        "    selection:",
    ]
    base += [f"        {k}: {q(v)}" for k, v in selection.items()]
    condition = "selection"
    for i, flt in enumerate(negated):
        base.append(f"    filter_{i}:")
        for k, v in flt.items():
            base.append(f"        {k}: {q(v)}")
        condition += f" and not filter_{i}"
    base.append(f"    condition: {condition}")
    base.append(f"level: {rule.severity}")

    docs = ["\n".join(base)]

    if rule.kind == "count":
        corr = [
            f"title: {q(rule.name)}",
            f"id: {_id(rule.name)}",
            "status: experimental",
            f"description: {q('Generated by SentryScript from rule ' + repr(rule.name) + '.')}",
            "correlation:",
            "    type: event_count",
            "    rules:",
            f"        - {base_name}",
            "    group-by:",
            f"        - {rule.group_by}",
            f"    timespan: {fmt_duration(rule.window)}",
            "    condition:",
            f"        gte: {rule.threshold}",
            f"level: {rule.severity}",
        ]
        docs.append("\n".join(corr))
    return docs

def to_sigma(rules):
    docs = []
    for rule in rules:
        docs += rule_to_sigma(rule)
    return "\n---\n".join(docs) + "\n"